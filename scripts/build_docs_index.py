"""Generate the documentation index files so every document is reachable.

Writes docs/README.md (top-level index), docs/research/INDEX.md (research notes,
protocols, figures, and status), and docs/research/results/INDEX.md (retained
evidence, including nested result folders). Run with --check to fail when an
index is stale.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
SECTIONS = {
    "guide": "Setup and workflows for users of the framework",
    "architecture": "Concepts and output contracts for users of the framework",
    "operations": "Refactor and verification records",
    "reference": "Reference data and the digest rebinding record",
    "thesis": "Thesis document",
}
TITLE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
SKIP_NAMES = {"README.md", "INDEX.md"}


def _title(path: Path) -> str:
    if path.suffix != ".md":
        return path.name
    match = TITLE.search(path.read_text(encoding="utf-8", errors="replace"))
    return match.group(1).strip() if match else path.name


def _link(path: Path, base: Path) -> str:
    label = _title(path) if path.suffix == ".md" else path.name
    return f"- [{label}]({path.relative_to(base).as_posix()})"


def _files_under(folder: Path) -> list[Path]:
    return sorted(p for p in folder.rglob("*") if p.is_file() and p.name not in SKIP_NAMES)


def build() -> dict[Path, str]:
    top = ["# Documentation", "", "Start here. This index lists every document under `docs/`.", ""]
    for folder, blurb in SECTIONS.items():
        base = DOCS / folder
        if not base.exists():
            continue
        top += [f"## {folder.capitalize()}", "", blurb + ".", ""]
        top += [_link(path, DOCS) for path in _files_under(base)]
        top.append("")
    top += [
        "## Research",
        "",
        "Research notes, protocols, contracts, and status: [research/INDEX.md](research/INDEX.md).",
        "Retained result files are indexed in [research/results/INDEX.md](research/results/INDEX.md).",
        "Result files are retained evidence and are not edited.",
        "",
        "Historical records:",
        "",
        "- The master research plan is no longer part of the tree. It is kept at the git tag `docs/master-research-plan-archive`.",
        "- The legacy 2025 code is kept at the git tag `archive/legacy-2025`.",
        "",
    ]

    research = DOCS / "research"
    research_lines = ["# Research index", "", "Generated by `scripts/build_docs_index.py`.", ""]
    for path in sorted(research.iterdir()):
        if path.is_file() and path.name not in SKIP_NAMES:
            research_lines.append(_link(path, research))
    research_lines += ["", "## Subfolders", ""]
    for sub in sorted(p for p in research.iterdir() if p.is_dir() and p.name != "results"):
        research_lines += ["", f"### {sub.name}/", ""]
        research_lines += [_link(path, research) for path in _files_under(sub)]
    research_lines += [
        "",
        "### results/",
        "",
        "Retained evidence, indexed in [results/INDEX.md](results/INDEX.md).",
        "",
    ]

    results = research / "results"
    result_lines = [
        "# Retained results index",
        "",
        "Generated by `scripts/build_docs_index.py`. These files are retained evidence.",
        "",
    ]
    result_lines += [_link(path, results) for path in _files_under(results)]

    outputs = {
        DOCS / "README.md": "\n".join(top),
        research / "INDEX.md": "\n".join(research_lines),
        results / "INDEX.md": "\n".join(result_lines),
    }
    return {path: text.rstrip("\n") + "\n" for path, text in outputs.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        raise SystemExit("stale documentation index: " + ", ".join(stale))
    print("docs indexes", "current" if args.check else "written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
